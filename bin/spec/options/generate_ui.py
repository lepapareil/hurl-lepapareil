#!/usr/bin/env python3
"""Generate the catalog of Hurl options used by Hurl UI.

Hurl UI does not hardcode the options of `hurl`: its preferences, the suggestions of its `[Options]` editor and the
command line it runs are built from this catalog, which is generated from the same `.option` files as the command
line parser, the man page and the completions of `hurl`.

Examples:
    $ bin/spec/options/generate_ui.py docs/spec/options/hurl/*.option > packages/hurlui_core/src/options/hurl.json
"""

import json
import os
import re
import sys
from functools import cmp_to_key

from generate_man import cmp_group
from option import Option

# Relative script file
SCRIPT_FILE = __file__[len(os.getcwd()) + 1 :]

# Options of an `[Options]` section, as parsed by Hurl.
SECTION_OPTIONS_FILE = "packages/hurl_core/src/ast/option.rs"

# Units of a duration, as parsed by Hurl.
DURATION_UNITS_FILE = "packages/hurl_core/src/types.rs"

# Kind of value of an option of an `[Options]` section, and its minimum, for each Rust type of `OptionKind`. `None`
# when the kind depends on the option (see `section_value_kind`).
SECTION_VALUE_KINDS = {
    "BooleanOption": ("boolean", None),
    "NaturalOption": ("integer", 0),
    # -1 is an infinite count.
    "CountOption": ("integer", -1),
    "DurationOption": ("duration", None),
    "VariableDefinition": ("variable", None),
    "VerbosityOption": None,
    "Template": None,
}


def generate_ui(
    options: list[Option], section_options: dict[str, str], duration_units: list[str]
) -> str:
    """Return the JSON catalog of options.

    Args:
        options: Command line options, parsed from the option files.
        section_options: Options of an `[Options]` section, with the Rust type of their value.
        duration_units: Units of a duration value.

    Returns:
        A JSON document.
    """
    check_section_options(options, section_options)
    by_name = {option.name: option for option in options}

    catalog = []
    for option in sorted(options, key=lambda o: o.long):
        kind, choices, minimum = value_kind(option)
        conflicts = [by_name[name].long for name in option.conflict or []]
        section_kind, section_min = None, None
        if option.long in section_options:
            section_kind, section_min = section_value_kind(
                option.long, section_options[option.long], choices
            )
        catalog.append(
            {
                "name": option.name,
                "long": option.long,
                "short": option.short,
                "kind": kind,
                "value": option.value,
                "default": option.value_default,
                "choices": choices,
                "min": minimum,
                "multi": option.append,
                "cli": True,
                "section": option.long in section_options,
                "section_kind": section_kind,
                "section_min": section_min,
                "help": option.help,
                "heading": option.help_heading,
                "conflicts": conflicts,
                "deprecated": option.deprecated,
                "experimental": option.experimental,
                "description": option.description,
            }
        )

    # Options which only exist in an `[Options]` section: they have no option file.
    cli_longs = {option.long for option in options}
    for long, value_type in sorted(section_options.items()):
        if long in cli_longs:
            continue
        section_kind, section_min = section_value_kind(long, value_type, [])
        catalog.append(
            {
                "name": long.replace("-", "_").replace(".", ""),
                "long": long,
                "short": None,
                "kind": "flag" if section_kind == "boolean" else "text",
                "value": None,
                "default": None,
                "choices": [],
                "min": None,
                "multi": False,
                "cli": False,
                "section": True,
                "section_kind": section_kind,
                "section_min": section_min,
                "help": None,
                "heading": None,
                "conflicts": [],
                "deprecated": False,
                "experimental": False,
                "description": "",
            }
        )

    headings = {option.help_heading for option in options if option.help_heading}
    document = {
        "comment": "Generated by " + SCRIPT_FILE + " - Do not modify",
        "headings": sorted(headings, key=cmp_to_key(cmp_group)),
        "duration_units": duration_units,
        "options": catalog,
    }
    return json.dumps(document, indent=2, ensure_ascii=False)


def value_kind(option: Option) -> tuple[str, list[str], int | None]:
    """Return the kind of value of an option, its accepted values and its minimum.

    The kind is `flag` (no value), `choice` (one of a list of values), `integer` or `text`.
    """
    if option.value is None:
        return "flag", [], None
    parser = option.value_parser
    if parser is None:
        return "text", [], None
    if parser.startswith("["):
        return "choice", json.loads(parser), None
    integer = re.fullmatch(
        r"clap::value_parser!\(([iu])\d+\)(?:\.range\((\d+)\.\.\))?", parser
    )
    if integer:
        sign, start = integer.groups()
        if start is not None:
            return "integer", [], int(start)
        return "integer", [], 0 if sign == "u" else None
    raise ValueError(
        f"{option.name}: value_parser <{parser}> is not supported by {SCRIPT_FILE}"
    )


def section_value_kind(
    long: str, value_type: str, choices: list[str]
) -> tuple[str, int | None]:
    """Return the kind of value of an option in an `[Options]` section, and its minimum.

    The kind is `boolean`, `integer`, `duration` (an integer and an optional unit), `choice` (one of the values of the
    command line option), `variable` (`name=value`) or `text`. Any of them can also be a `{{placeholder}}`.

    Args:
        long: Long name of the option.
        value_type: Rust type of the value, in `OptionKind`.
        choices: Values accepted by the command line option, if it has a list of them.
    """
    if value_type not in SECTION_VALUE_KINDS:
        raise ValueError(
            f"{long}: type <{value_type}> of {SECTION_OPTIONS_FILE} is not supported by {SCRIPT_FILE}"
        )
    kind = SECTION_VALUE_KINDS[value_type]
    if kind is not None:
        return kind
    if value_type == "VerbosityOption" and len(choices) == 0:
        raise ValueError(f"{long}: no value_parser listing the values of this option")
    return ("choice" if choices else "text"), None


def parse_duration_units(source: str) -> list[str]:
    """Return the units of a duration.

    Args:
        source: Rust source defining `DurationUnit` and its `Display`.
    """
    units = re.findall(r'DurationUnit::\w+ => write!\(f, "(\w+)"\)', source)
    if len(units) == 0:
        raise ValueError(f"DurationUnit can not be parsed in {DURATION_UNITS_FILE}")
    return units


def parse_section_options(source: str) -> dict[str, str]:
    """Return the options of an `[Options]` section, with the Rust type of their value.

    Args:
        source: Rust source defining `OptionKind` and `OptionKind::identifier`.
    """
    kinds = re.search(r"pub enum OptionKind \{(.*?)\n\}", source, re.DOTALL)
    identifier = re.search(
        r"pub fn identifier\(&self\).*?\{(.*?)\n    \}", source, re.DOTALL
    )
    if kinds is None or identifier is None:
        raise ValueError(f"OptionKind can not be found in {SECTION_OPTIONS_FILE}")
    value_types = dict(re.findall(r"(\w+)\((\w+)\)", kinds.group(1)))
    identifiers = re.findall(
        r'OptionKind::(\w+)\(_\) => "([^"]+)"', identifier.group(1)
    )
    if len(identifiers) == 0 or len(identifiers) != len(value_types):
        raise ValueError(f"OptionKind can not be parsed in {SECTION_OPTIONS_FILE}")
    return {long: value_types[variant] for variant, long in identifiers}


def check_section_options(options: list[Option], section_options: dict[str, str]):
    """Check that option files and Hurl agree on the options of an `[Options]` section."""
    for option in options:
        if option.cli_only and option.long in section_options:
            raise ValueError(
                f"{option.name}: cli_only option is an option of [Options] section in {SECTION_OPTIONS_FILE}"
            )
        if not option.cli_only and option.long not in section_options:
            raise ValueError(
                f"{option.name}: option is not cli_only and is not an option of [Options] section in "
                f"{SECTION_OPTIONS_FILE}"
            )


def main():
    """Entry point: parse option files from command-line arguments and print the catalog."""
    if len(sys.argv) < 2:
        print("usage: generate_ui.py OPTION_FILE1 OPTION_FILE2 ...")
        sys.exit(1)
    options = [Option.parse_file(filename) for filename in sys.argv[1:]]
    with open(SECTION_OPTIONS_FILE) as f:
        section_options = parse_section_options(f.read())
    with open(DURATION_UNITS_FILE) as f:
        duration_units = parse_duration_units(f.read())
    print(generate_ui(options, section_options, duration_units))


if __name__ == "__main__":
    main()
