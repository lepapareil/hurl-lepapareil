//! Options of `hurl`, shared with Hurl itself.
//!
//! Nothing about the options of `hurl` is written by hand in Hurl UI: their
//! names, values, defaults and documentation come from `hurl.json`. This
//! catalog is generated by `bin/spec/options/generate_ui.py` from the option
//! files of `docs/spec/options/hurl`, as are the command line parser, the man
//! page and the completions of `hurl`. An option added to Hurl is therefore
//! offered by the preferences, suggested in `[Options]` sections and accepted
//! on the command line without any change here.
//!
//! What is written here is what belongs to the application: the options it
//! sets itself for every run (`MANAGED`), which refer to the catalog by
//! name and are checked against it by the tests.

use serde::{Deserialize, Serialize};
use serde_json::{Map, Value};
use std::sync::OnceLock;

/// Generated by `bin/spec/options/generate_ui.py`.
const CATALOG: &str = include_str!("hurl.json");

// Names (in their option file) of the options used by the runner.
pub const FROM_ENTRY: &str = "from_entry";
pub const NO_COLOR: &str = "no_color";
pub const NO_OUTPUT: &str = "no_output";
pub const REPORT_JSON: &str = "report_json";
pub const TO_ENTRY: &str = "to_entry";
pub const VARIABLES_FILE: &str = "variables_file";
pub const VERBOSE: &str = "verbose";
pub const VERY_VERBOSE: &str = "very_verbose";

/// Options which cannot be set in the preferences, by the name of their
/// option file.
const MANAGED: &[&str] = &[
    // Set by the runner for every run: the result of a run is read from the
    // JSON report.
    REPORT_JSON,
    NO_OUTPUT,
    NO_COLOR,
    // Set by the runner to send a single request.
    FROM_ENTRY,
    TO_ENTRY,
    // Set from the log level of the preferences.
    VERBOSE,
    VERY_VERBOSE,
    "verbosity",
    // In conflict with the options of the runner, or changing what `hurl`
    // writes on its standard output and error, which the runner reads.
    "color",
    "include",
    "json",
    "no_pretty",
    "output",
    "pretty",
    "progress_bar",
    "test",
    // Runs other files than the one which was asked.
    "glob",
    // Secrets belong to environments, which keep them out of the preferences
    // and of the command line.
    "secret",
];

/// Kind of value of an option.
#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum Kind {
    /// No value: the option is set or not.
    Flag,
    /// One of `choices`.
    Choice,
    /// An integer, not lower than `min` if any.
    Integer,
    /// Any text.
    Text,
}

/// Kind of value of an option in an `[Options]` section. Whatever the kind,
/// the value can also be a `{{placeholder}}`.
#[derive(Clone, Copy, Debug, Deserialize, Eq, PartialEq, Serialize)]
#[serde(rename_all = "lowercase")]
pub enum SectionKind {
    /// `true` or `false`.
    Boolean,
    /// An integer, not lower than `section_min`.
    Integer,
    /// An integer followed by an optional unit (`duration_units` of the
    /// catalog).
    Duration,
    /// One of `choices`.
    Choice,
    /// `name=value`.
    Variable,
    /// Any text.
    Text,
}

/// An option of `hurl`, as described by its option file.
#[derive(Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct OptionSpec {
    /// Name of the option file, used to refer to an option in the code.
    pub name: String,
    /// Long name: `--long` on the command line, `long: value` in an
    /// `[Options]` section. Identifies the option in the preferences.
    pub long: String,
    pub short: Option<String>,
    pub kind: Kind,
    /// Placeholder of the value, as shown by `hurl --help`.
    pub value: Option<String>,
    pub default: Option<String>,
    pub choices: Vec<String>,
    pub min: Option<i64>,
    /// Whether the option can be given several times.
    pub multi: bool,
    /// Whether this is an option of the command line.
    pub cli: bool,
    /// Whether this is an option of an `[Options]` section.
    pub section: bool,
    /// Kind of its value in an `[Options]` section, from the type Hurl
    /// parses it into.
    pub section_kind: Option<SectionKind>,
    pub section_min: Option<i64>,
    pub help: Option<String>,
    pub heading: Option<String>,
    /// Long names of the options which cannot be used with this one.
    pub conflicts: Vec<String>,
    pub deprecated: bool,
    pub experimental: bool,
    /// Documentation of the man page, in Markdown.
    pub description: String,
    /// Whether the option is set by the application itself (see
    /// `MANAGED`). Not in the generated catalog.
    #[serde(default)]
    pub managed: bool,
}

/// All the options of `hurl`.
#[derive(Debug, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub struct Catalog {
    /// Notice of the generator, for the readers of the generated file.
    #[serde(skip_serializing)]
    pub comment: String,
    /// Headings of `hurl --help`, in their order.
    pub headings: Vec<String>,
    /// Units of a duration value, in an `[Options]` section.
    pub duration_units: Vec<String>,
    /// Sorted by long name.
    pub options: Vec<OptionSpec>,
}

fn parse_catalog() -> Result<Catalog, String> {
    let mut catalog: Catalog = serde_json::from_str(CATALOG).map_err(|e| e.to_string())?;
    for name in MANAGED {
        let option = catalog
            .options
            .iter_mut()
            .find(|option| option.name == *name)
            .ok_or_else(|| format!("unknown hurl option: {name}"))?;
        option.managed = true;
    }
    Ok(catalog)
}

/// The catalog of options. It is generated and embedded in the binary: it
/// can only be invalid if the generator is, which the tests would tell.
pub fn catalog() -> &'static Catalog {
    static CATALOG: OnceLock<Catalog> = OnceLock::new();
    CATALOG.get_or_init(|| parse_catalog().expect("generated catalog of hurl options"))
}

/// The option with this long name.
pub fn find(long: &str) -> Option<&'static OptionSpec> {
    catalog().options.iter().find(|option| option.long == long)
}

/// Command line argument (`--long`) of the option named `name` in its option
/// file.
pub fn cli(name: &str) -> Result<String, String> {
    catalog()
        .options
        .iter()
        .find(|option| option.name == name && option.cli)
        .map(|option| format!("--{}", option.long))
        .ok_or_else(|| format!("unknown hurl option: {name}"))
}

/// Value of an option on the command line: `None` when there is none.
fn text(option: &OptionSpec, value: &Value) -> Result<Option<String>, String> {
    match value {
        Value::Null => Ok(None),
        Value::String(text) => Ok(Some(text.trim().to_string()).filter(|text| !text.is_empty())),
        Value::Number(number) => Ok(Some(number.to_string())),
        _ => Err(format!("invalid value for --{}: {value}", option.long)),
    }
}

/// Command line arguments setting these options, given by long name: a
/// boolean for a flag, a string or a number for a value, and an array of
/// them for an option which can be given several times. Options which are
/// not set (`false`, `null`, an empty string or array) add nothing.
///
/// Only the shape of the values is checked here: `hurl` is the one which
/// knows what a valid value is, and reports it.
pub fn arguments(values: &Map<String, Value>) -> Result<Vec<String>, String> {
    if let Some(unknown) = values.keys().find(|long| find(long).is_none()) {
        return Err(format!("unknown hurl option: --{unknown}"));
    }
    let mut args = vec![];
    // In the order of the catalog: the same options give the same command.
    for option in &catalog().options {
        let Some(value) = values.get(&option.long) else {
            continue;
        };
        let flag = format!("--{}", option.long);
        if !option.cli {
            return Err(format!("{} is not a command line option", option.long));
        }
        if option.managed {
            return Err(format!("{flag} is set by Hurl UI itself"));
        }
        match (option.kind, value) {
            (Kind::Flag, Value::Bool(set)) => {
                if *set {
                    args.push(flag);
                }
            }
            (Kind::Flag, Value::Null) => {}
            (Kind::Flag, _) => return Err(format!("invalid value for {flag}: {value}")),
            (_, Value::Array(items)) if option.multi => {
                for item in items {
                    if let Some(text) = text(option, item)? {
                        args.extend([flag.clone(), text]);
                    }
                }
            }
            _ => {
                if let Some(text) = text(option, value)? {
                    args.extend([flag, text]);
                }
            }
        }
    }
    Ok(args)
}

impl OptionSpec {
    /// Whether the option can be set by the user for a run: in the
    /// preferences, or in the options file of a folder or of a Hurl file.
    pub fn settable(&self) -> bool {
        self.cli && !self.managed && !self.deprecated && !self.experimental
    }
}

// --- Options files ----------------------------------------------------------
//
// Options of a folder or of a Hurl file are kept next to it, in a file
// written as the configuration file of Hurl (`~/.config/hurl/config`): one
// option per line, `--name` for a flag and `--name value` otherwise, with `#`
// comments.

/// Options of an options file, by long name (as taken by [`arguments`]),
/// and the lines which are not such an option (comments, options this
/// version of Hurl does not have): they are kept when the file is written.
pub fn parse_file(text: &str) -> (Map<String, Value>, Vec<String>) {
    let mut values = Map::new();
    let mut others = vec![];
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() {
            continue;
        }
        match parse_line(trimmed) {
            Some((option, None)) => {
                values.insert(option.long.clone(), Value::Bool(true));
            }
            Some((option, Some(value))) if option.multi => {
                let list = values
                    .entry(option.long.clone())
                    .or_insert_with(|| Value::Array(vec![]));
                if let Value::Array(items) = list {
                    items.push(Value::String(value));
                }
            }
            Some((option, Some(value))) => {
                values.insert(option.long.clone(), Value::String(value));
            }
            None => others.push(line.to_string()),
        }
    }
    (values, others)
}

/// An option line: the option, and its value if it takes one.
fn parse_line(line: &str) -> Option<(&'static OptionSpec, Option<String>)> {
    let rest = line.strip_prefix("--")?;
    let end = rest
        .find(|c: char| !(c.is_alphanumeric() || "-_.".contains(c)))
        .unwrap_or(rest.len());
    let (name, rest) = rest.split_at(end);
    let option = find(name).filter(|option| option.settable())?;
    if option.kind == Kind::Flag {
        let rest = rest.trim();
        return (rest.is_empty() || rest.starts_with('#')).then_some((option, None));
    }
    // The value follows a space or `=`.
    let value = rest.strip_prefix('=').or_else(|| {
        rest.starts_with([' ', '\t'])
            .then(|| rest.trim_start_matches([' ', '\t']))
    })?;
    let value = match value.strip_prefix('"') {
        // Quoted: up to the closing quote, a comment may follow.
        Some(quoted) => {
            let (value, after) = quoted.split_once('"')?;
            let after = after.trim();
            if !(after.is_empty() || after.starts_with('#')) {
                return None;
            }
            value.trim()
        }
        None => value.trim(),
    };
    (!value.is_empty()).then(|| (option, Some(value.to_string())))
}

/// Text of an options file: the lines kept from the file it replaces, then
/// the options, in the order of the catalog. Empty when there is nothing to
/// write.
pub fn format_file(values: &Map<String, Value>, others: &[String]) -> Result<String, String> {
    // Same checks as for a command line.
    let args = arguments(values)?;
    let mut text = String::new();
    for line in others {
        text.push_str(line);
        text.push('\n');
    }
    let mut args = args.into_iter().peekable();
    while let Some(flag) = args.next() {
        let name = flag.trim_start_matches("--");
        let valued = find(name).is_some_and(|option| option.kind != Kind::Flag);
        text.push_str(&flag);
        if valued {
            let value = args.next().unwrap_or_default();
            // One option per line, and a value which starts with a quote
            // would be read as a quoted one.
            if value.contains('\n') || value.starts_with('"') {
                return Err(format!("{flag}: this value cannot be written: {value}"));
            }
            text.push(' ');
            text.push_str(&value);
        }
        text.push('\n');
    }
    Ok(text)
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    fn values(value: Value) -> Map<String, Value> {
        value.as_object().unwrap().clone()
    }

    #[test]
    fn catalog_is_valid() {
        let catalog = parse_catalog().unwrap();
        assert!(catalog.comment.starts_with("Generated by "));
        assert!(!catalog.headings.is_empty());
        assert!(catalog.duration_units.iter().any(|unit| unit == "ms"));

        let longs: Vec<&str> = catalog.options.iter().map(|o| o.long.as_str()).collect();
        let mut unique = longs.clone();
        unique.sort_unstable();
        unique.dedup();
        assert_eq!(unique.len(), longs.len());

        for option in &catalog.options {
            assert!(option.cli || option.section, "{}", option.long);
            assert_eq!(option.section, option.section_kind.is_some());
            assert_eq!(
                option.section_kind == Some(SectionKind::Integer),
                option.section_min.is_some()
            );
            if option.section_kind == Some(SectionKind::Choice) {
                assert!(!option.choices.is_empty(), "{}", option.long);
            }
            // A flag of the command line is a boolean of an `[Options]`
            // section.
            if option.section && option.kind == Kind::Flag {
                assert_eq!(option.section_kind, Some(SectionKind::Boolean));
            }
            assert_eq!(option.kind == Kind::Choice, !option.choices.is_empty());
            assert_eq!(option.kind == Kind::Flag, option.value.is_none());
            if let Some(heading) = &option.heading {
                assert!(catalog.headings.contains(heading), "{}", option.long);
            }
            for conflict in &option.conflicts {
                assert!(longs.contains(&conflict.as_str()), "{}", option.long);
            }
        }
    }

    /// The options the application relies on: if one of them is renamed or
    /// removed in Hurl, this is where it shows.
    #[test]
    fn options_of_the_runner_are_in_the_catalog() {
        for name in MANAGED {
            let option = catalog().options.iter().find(|o| o.name == *name);
            assert!(option.is_some_and(|o| o.managed && o.cli), "{name}");
        }
        let flags = [NO_COLOR, NO_OUTPUT, VERBOSE, VERY_VERBOSE];
        let valued = [FROM_ENTRY, REPORT_JSON, TO_ENTRY, VARIABLES_FILE];
        for name in flags.iter().chain(&valued) {
            let option = catalog().options.iter().find(|o| o.name == *name).unwrap();
            assert_eq!(option.kind == Kind::Flag, flags.contains(name), "{name}");
        }
        assert_eq!(cli(REPORT_JSON).unwrap(), "--report-json");
        assert!(cli("unknown").is_err());
        assert!(!find("variables-file").unwrap().managed);
    }

    #[test]
    fn arguments_follow_the_catalog() {
        let args = arguments(&values(json!({
            "retry": 3,
            "insecure": true,
            "location": false,
            "max-time": " 30s ",
            "proxy": "",
            "header": ["A: 1", "", "B: 2"],
            "tls-max": null,
        })))
        .unwrap();
        assert_eq!(
            args,
            [
                "--header",
                "A: 1",
                "--header",
                "B: 2",
                "--insecure",
                "--max-time",
                "30s",
                "--retry",
                "3"
            ]
        );
        assert_eq!(arguments(&Map::new()).unwrap(), Vec::<String>::new());
    }

    #[test]
    fn options_files_are_read_and_written() {
        let text = "# Options of the API\n\
                    --insecure\n\
                    --location   # follow redirects\n\
                    --header X-A: 1\n\
                    --header=\"X-B: 2\"  # quoted\n\
                    \n\
                    --max-time=30s\n\
                    --retry 3\n\
                    --retry 5\n\
                    --unknown-option 1\n\
                    --report-json /tmp\n\
                    --insecure yes\n\
                    --proxy\n\
                    not an option\n";
        let (parsed, others) = parse_file(text);
        assert_eq!(
            Value::Object(parsed.clone()),
            json!({
                "insecure": true,
                "location": true,
                "header": ["X-A: 1", "X-B: 2"],
                "max-time": "30s",
                "retry": "5",
            })
        );
        // What is not an option which can be set is kept as it is.
        assert_eq!(
            others,
            [
                "# Options of the API",
                "--unknown-option 1",
                "--report-json /tmp",
                "--insecure yes",
                "--proxy",
                "not an option"
            ]
        );
        let written = format_file(&parsed, &others[..1]).unwrap();
        assert_eq!(
            written,
            "# Options of the API\n\
             --header X-A: 1\n\
             --header X-B: 2\n\
             --insecure\n\
             --location\n\
             --max-time 30s\n\
             --retry 5\n"
        );
        // Reading what was written gives the same options.
        assert_eq!(parse_file(&written).0, parsed);
        assert_eq!(format_file(&Map::new(), &[]).unwrap(), "");

        let invalid = |value: Value| format_file(&values(value), &[]).unwrap_err();
        assert!(invalid(json!({ "proxy": "\"quoted" })).contains("cannot be written"));
        assert!(invalid(json!({ "header": ["a\nb"] })).contains("cannot be written"));
        assert!(invalid(json!({ "report-json": "/tmp" })).contains("set by Hurl UI"));
    }

    #[test]
    fn invalid_options_are_refused() {
        let error = |value: Value| arguments(&values(value)).unwrap_err();
        assert_eq!(
            error(json!({ "nope": true })),
            "unknown hurl option: --nope"
        );
        assert_eq!(
            error(json!({ "report-json": "/tmp" })),
            "--report-json is set by Hurl UI itself"
        );
        assert_eq!(
            error(json!({ "skip": true })),
            "skip is not a command line option"
        );
        assert_eq!(
            error(json!({ "insecure": "yes" })),
            "invalid value for --insecure: \"yes\""
        );
        assert_eq!(
            error(json!({ "max-time": ["1", "2"] })),
            "invalid value for --max-time: [\"1\",\"2\"]"
        );
        assert_eq!(
            error(json!({ "header": [true] })),
            "invalid value for --header: true"
        );
    }
}
